const fs = require("node:fs/promises");
const path = require("node:path");

const ROOT = path.resolve(__dirname, "..");
const OUTPUT = path.join(ROOT, "fallback-data.js");
const BASE_URL = "https://raw.githubusercontent.com/PokeAPI/pokeapi/master/data/v2/csv";
const SPANISH_LANGUAGE_ID = "7";

async function main() {
  global.window = {};
  require(OUTPUT);

  const pokemon = window.LOCAL_POKEMON;
  const types = window.LOCAL_TYPES;
  const typeRelations = window.LOCAL_TYPE_RELATIONS;

  console.log("Downloading CSV translation tables...");
  const csv = await loadCsvFiles([
    "abilities.csv",
    "ability_names.csv",
    "moves.csv",
    "move_names.csv",
    "pokemon.csv",
    "pokemon_species.csv",
    "pokemon_species_flavor_text.csv",
    "pokemon_species_names.csv",
    "types.csv",
    "type_names.csv",
  ]);

  const abilityTranslations = translationsByIdentifier(
    csv["abilities.csv"],
    csv["ability_names.csv"],
    "ability_id",
  );
  const moveTranslations = translationsByIdentifier(csv["moves.csv"], csv["move_names.csv"], "move_id");
  const typeTranslations = translationsByIdentifier(csv["types.csv"], csv["type_names.csv"], "type_id");
  const speciesNames = speciesNamesById(csv["pokemon_species_names.csv"]);
  const speciesInfo = speciesInfoById(csv["pokemon_species.csv"]);
  const flavorText = flavorTextBySpeciesId(csv["pokemon_species_flavor_text.csv"]);
  const pokemonRows = Object.fromEntries(csv["pokemon.csv"].map((row) => [row.identifier, row]));

  for (const [type, relation] of Object.entries(typeRelations)) {
    relation.label = typeTranslations[type] || formatName(type);
  }

  for (const entry of pokemon) {
    const row = pokemonRows[entry.name];
    if (!row) continue;

    const speciesName = speciesNames[row.species_id]?.name || formatName(entry.species?.name || entry.name);
    const info = speciesInfo[row.species_id] || {};

    entry.height = Number(row.height || 0);
    entry.weight = Number(row.weight || 0);
    entry.base_experience = Number(row.base_experience || 0);
    entry.displayName = displayNameForForm(entry.name, speciesName);
    entry.genus = speciesNames[row.species_id]?.genus || "";
    entry.flavor = flavorText[row.species_id] || "";
    entry.generation = info.generation_id ? `gen-${info.generation_id}` : "";
    entry.flags = {
      baby: info.is_baby === "1",
      legendary: info.is_legendary === "1",
      mythical: info.is_mythical === "1",
    };
  }

  const translations = {
    abilities: abilityTranslations,
    moves: moveTranslations,
    pokemon: Object.fromEntries(pokemon.map((entry) => [entry.name, entry.displayName])),
    types: typeTranslations,
  };

  const output = [
    "// Generated by scripts/build-fallback-data.js and scripts/apply-csv-translations.js. Do not edit by hand.",
    `const LOCAL_TYPES = ${JSON.stringify(types)};`,
    `const LOCAL_TYPE_RELATIONS = ${JSON.stringify(typeRelations)};`,
    `const LOCAL_POKEMON = ${JSON.stringify(pokemon)};`,
    `const LOCAL_TRANSLATIONS = ${JSON.stringify(translations)};`,
    "",
    "window.LOCAL_TYPES = LOCAL_TYPES;",
    "window.LOCAL_TYPE_RELATIONS = LOCAL_TYPE_RELATIONS;",
    "window.LOCAL_POKEMON = LOCAL_POKEMON;",
    "window.LOCAL_TRANSLATIONS = LOCAL_TRANSLATIONS;",
    "",
  ].join("\n");

  await fs.writeFile(OUTPUT, output, "utf8");
  console.log(`Updated ${path.relative(ROOT, OUTPUT)} with Spanish translations.`);
}

async function loadCsvFiles(fileNames) {
  const pairs = await Promise.all(
    fileNames.map(async (fileName) => {
      const response = await fetch(`${BASE_URL}/${fileName}`);
      if (!response.ok) throw new Error(`Failed to download ${fileName}: ${response.status}`);
      return [fileName, parseCsv(await response.text())];
    }),
  );

  return Object.fromEntries(pairs);
}

function translationsByIdentifier(baseRows, translationRows, idColumn) {
  const identifiersById = Object.fromEntries(baseRows.map((row) => [row.id, row.identifier]));
  const output = {};

  for (const row of translationRows) {
    if (row.local_language_id !== SPANISH_LANGUAGE_ID) continue;

    const identifier = identifiersById[row[idColumn]];
    if (identifier && row.name) {
      output[identifier] = row.name;
    }
  }

  return output;
}

function speciesNamesById(rows) {
  const output = {};

  for (const row of rows) {
    if (row.local_language_id !== SPANISH_LANGUAGE_ID) continue;
    output[row.pokemon_species_id] = {
      genus: row.genus || "",
      name: row.name || "",
    };
  }

  return output;
}

function speciesInfoById(rows) {
  return Object.fromEntries(rows.map((row) => [row.id, row]));
}

function flavorTextBySpeciesId(rows) {
  const output = {};

  for (const row of rows) {
    if (row.language_id !== SPANISH_LANGUAGE_ID || output[row.species_id]) continue;
    output[row.species_id] = row.flavor_text.replace(/[\f\n\r\t ]+/g, " ").trim();
  }

  return output;
}

function parseCsv(text) {
  const rows = [];
  let row = [];
  let value = "";
  let quoted = false;

  for (let index = 0; index < text.length; index += 1) {
    const char = text[index];
    const next = text[index + 1];

    if (quoted && char === '"' && next === '"') {
      value += '"';
      index += 1;
      continue;
    }

    if (char === '"') {
      quoted = !quoted;
      continue;
    }

    if (!quoted && char === ",") {
      row.push(value);
      value = "";
      continue;
    }

    if (!quoted && (char === "\n" || char === "\r")) {
      if (char === "\r" && next === "\n") index += 1;
      row.push(value);
      rows.push(row);
      row = [];
      value = "";
      continue;
    }

    value += char;
  }

  if (value || row.length) {
    row.push(value);
    rows.push(row);
  }

  const headers = rows.shift();
  return rows
    .filter((entry) => entry.length === headers.length)
    .map((entry) => Object.fromEntries(headers.map((header, index) => [header, entry[index]])));
}

function displayNameForForm(name, speciesName) {
  if (!name.includes("-")) return speciesName;

  const suffix = name
    .split("-")
    .slice(1)
    .join(" ")
    .replace(/\bgmax\b/g, "gigamax")
    .replace(/\balola\b/g, "alola")
    .replace(/\bgalar\b/g, "galar")
    .replace(/\bhisui\b/g, "hisui")
    .replace(/\bpaldea\b/g, "paldea");

  return `${speciesName} ${suffix}`.trim();
}

function formatName(name) {
  return name
    .split("-")
    .map((part) => part.charAt(0).toUpperCase() + part.slice(1))
    .join(" ");
}

main().catch((error) => {
  console.error(error);
  process.exitCode = 1;
});
