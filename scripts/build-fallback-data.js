const fs = require("node:fs/promises");
const path = require("node:path");

const API = "https://pokeapi.co/api/v2";
const ROOT = path.resolve(__dirname, "..");
const IMAGE_DIR = path.join(ROOT, "assets", "pokemon");
const OUTPUT = path.join(ROOT, "fallback-data.js");
const CONCURRENCY = 18;
const REQUEST_DELAY_MS = 35;

const sleep = (ms) => new Promise((resolve) => setTimeout(resolve, ms));

async function main() {
  await fs.mkdir(IMAGE_DIR, { recursive: true });

  console.log("Loading type chart...");
  const typeList = await fetchJson(`${API}/type?limit=100`);
  const types = typeList.results
    .map((type) => type.name)
    .filter((type) => !["unknown", "shadow"].includes(type))
    .sort();

  const typeDetails = await mapWithConcurrency(types, async (type) => {
    const details = await fetchJson(`${API}/type/${type}`);
    return [
      type,
      {
        doubleTo: details.damage_relations.double_damage_to.map((entry) => entry.name),
        halfTo: details.damage_relations.half_damage_to.map((entry) => entry.name),
        noTo: details.damage_relations.no_damage_to.map((entry) => entry.name),
      },
    ];
  });
  const typeRelations = Object.fromEntries(typeDetails);

  console.log("Loading Pokemon index...");
  const pokemonList = await fetchJson(`${API}/pokemon?limit=2000`);
  const entries = pokemonList.results.filter((entry) => !entry.name.includes("-totem"));
  console.log(`Downloading ${entries.length} Pokemon entries and artwork...`);

  let completed = 0;
  const pokemon = await mapWithConcurrency(entries, async (entry) => {
    const details = await fetchJson(entry.url);
    const imageUrl =
      details.sprites.other?.["official-artwork"]?.front_default ||
      details.sprites.front_default ||
      "";
    const localImage = imageUrl ? await downloadPokemonImage(details, imageUrl) : "";

    completed += 1;
    if (completed % 50 === 0 || completed === entries.length) {
      console.log(`Downloaded ${completed}/${entries.length}`);
    }

    return {
      id: details.id,
      name: details.name,
      sprites: {
        front_default: localImage,
        other: {
          "official-artwork": {
            front_default: localImage,
          },
        },
      },
      types: details.types.map((slot) => ({
        slot: slot.slot,
        type: { name: slot.type.name },
      })),
      abilities: details.abilities.map((slot) => ({
        is_hidden: slot.is_hidden,
        slot: slot.slot,
        ability: { name: slot.ability.name },
      })),
      moves: details.moves.map((slot) => ({
        move: { name: slot.move.name },
      })),
      stats: details.stats.map((slot) => ({
        base_stat: slot.base_stat,
        stat: { name: slot.stat.name },
      })),
    };
  });

  pokemon.sort((a, b) => a.id - b.id || a.name.localeCompare(b.name));
  fillMissingImages(pokemon);

  const output = [
    "// Generated by scripts/build-fallback-data.js. Do not edit by hand.",
    `const LOCAL_TYPES = ${JSON.stringify(types)};`,
    `const LOCAL_TYPE_RELATIONS = ${JSON.stringify(typeRelations)};`,
    `const LOCAL_POKEMON = ${JSON.stringify(pokemon)};`,
    "",
    "window.LOCAL_TYPES = LOCAL_TYPES;",
    "window.LOCAL_TYPE_RELATIONS = LOCAL_TYPE_RELATIONS;",
    "window.LOCAL_POKEMON = LOCAL_POKEMON;",
    "",
  ].join("\n");

  await fs.writeFile(OUTPUT, output, "utf8");
  console.log(`Wrote ${path.relative(ROOT, OUTPUT)}`);
  console.log(`Images saved in ${path.relative(ROOT, IMAGE_DIR)}`);
}

function fillMissingImages(pokemon) {
  const byName = new Map(pokemon.map((entry) => [entry.name, entry]));

  for (const entry of pokemon) {
    if (entry.sprites.front_default) continue;

    const fallback = imageFallbackNames(entry.name)
      .map((name) => byName.get(name))
      .find((candidate) => candidate?.sprites.front_default);

    if (fallback) {
      entry.sprites.front_default = fallback.sprites.front_default;
      entry.sprites.other["official-artwork"].front_default = fallback.sprites.front_default;
    }
  }
}

function imageFallbackNames(name) {
  return [
    name.replace(/-(limited|sprinting|swimming|gliding)-build$/, ""),
    name.replace(/-(low-power|drive|aquatic|glide)-mode$/, ""),
    name.replace(/-mega$/, ""),
    name.split("-")[0],
  ];
}

async function fetchJson(url, attempt = 1) {
  await sleep(REQUEST_DELAY_MS);
  const response = await fetch(url);

  if (!response.ok) {
    if (attempt < 4 && [429, 500, 502, 503, 504].includes(response.status)) {
      await sleep(500 * attempt);
      return fetchJson(url, attempt + 1);
    }
    throw new Error(`Request failed ${response.status}: ${url}`);
  }

  return response.json();
}

async function downloadPokemonImage(details, imageUrl) {
  const safeName = details.name.replace(/[^a-z0-9-]/g, "-");
  const extension = imageUrl.split(".").pop().split("?")[0] || "png";
  const fileName = `${String(details.id).padStart(5, "0")}-${safeName}.${extension}`;
  const absolutePath = path.join(IMAGE_DIR, fileName);
  const relativePath = `assets/pokemon/${fileName}`;

  try {
    await fs.access(absolutePath);
    return relativePath;
  } catch {
    // File does not exist yet.
  }

  const response = await fetch(imageUrl);
  if (!response.ok) return "";

  const buffer = Buffer.from(await response.arrayBuffer());
  await fs.writeFile(absolutePath, buffer);
  return relativePath;
}

async function mapWithConcurrency(items, mapper) {
  const results = new Array(items.length);
  let index = 0;

  async function worker() {
    while (index < items.length) {
      const current = index;
      index += 1;
      results[current] = await mapper(items[current], current);
    }
  }

  await Promise.all(
    Array.from({ length: Math.min(CONCURRENCY, items.length) }, () => worker()),
  );

  return results;
}

main().catch((error) => {
  console.error(error);
  process.exitCode = 1;
});
